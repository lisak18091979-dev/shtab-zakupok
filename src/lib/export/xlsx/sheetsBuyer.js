export function lightSheet(items) {
  const sh = new Sheet('Светофор', [34, 13, 20, 11, 12, 12, 13, 12, 62, 10])
    .title('Светофор поставок', 'Красное: непокрытые дни есть и позиция остановит линию. Жёлтое: непокрытые дни есть. Зелёное: запаса хватает. Светлые ячейки заполняете вы.', 'A2:I2');
  sh.set('A4', 'Красных позиций', 8).f('B4', `COUNTIF(${rg('G')},"КРАСНОЕ")`, 11).set('C4', 'Риск не закрыт, млн ₽', 8).f('D4', `SUM(${rg('H')})`, 9)
    .set('E4', 'Можно не трогать', 8).f('F4', `COUNTIF(${rg('G')},"ЗЕЛЁНОЕ")`, 11);
  sh.set('A5', 'Сегодня беру в работу:', 8).f('B5', `IF(B4=0,"Красного нет",INDEX(${rg('A')},MATCH(MAX(${rg('J')}),${rg('J')},0)))`, 12, true).merge('B5:I5');
  sh.head(7, ['Позиция или поставщик', 'Цена дня простоя, млн ₽', 'Что будет без поставки', 'Запас, дней', 'Срок замены, дней', 'Непокрыто, дней', 'Статус', 'Риск, млн ₽', 'Действие сегодня', 'Служебно']);
  for (let r = R1; r <= R2; r++) {
    const it = items[r - R1];
    sh.set(`A${r}`, it?.name, 4).set(`B${r}`, num(it?.dayCost), 5).set(`C${r}`, it?.effect, 4).set(`D${r}`, num(it?.stock), 5).set(`E${r}`, num(it?.replace), 5)
      .f(`F${r}`, `IF(A${r}="","",MAX(0,E${r}-D${r}))`)
      .f(`G${r}`, `IF(A${r}="","",IF(F${r}=0,"ЗЕЛЁНОЕ",IF(C${r}="Остановит линию","КРАСНОЕ","ЖЁЛТОЕ")))`, 7, true)
      .f(`H${r}`, `IF(A${r}="","",F${r}*B${r}*${FACT(r)})`)
      .f(`I${r}`, `IF(G${r}="КРАСНОЕ","Сегодня: звонок поставщику, второй источник, частичная отгрузка, оплата под отгрузку.",IF(G${r}="ЖЁЛТОЕ","На этой неделе: подтвердить сроки, найти запасной вариант.",IF(G${r}="ЗЕЛЁНОЕ","Не трогать. Силы беречь.","")))`, 7, true)
      .f(`J${r}`, `IF(G${r}="КРАСНОЕ",H${r},-1)`);
  }
  return sh.list(rg('C'), EFFECTS).cond(rg('G'), [{ eq: 'КРАСНОЕ', dxf: 0 }, { eq: 'ЖЁЛТОЕ', dxf: 1 }, { eq: 'ЗЕЛЁНОЕ', dxf: 2 }]);
}

export function stressSheet() {
  const sh = new Sheet('Стресс тест', [34, 12, 22, 14, 10]).title('Стресс тест', 'Что будет, если поставки оборвутся на выбранный срок (лист «Параметры»)', 'A2:D2');
  sh.set('A4', 'Срок обрыва, дней', 8).f('B4', `'Параметры'!B6`, 11).set('C4', 'Потери всего, млн ₽', 8).f('D4', `SUM(D${R1}:D${R2})`, 9);
  sh.set('A5', 'Падает первой:', 8).f('B5', `IF(D4=0,"Ничего не падает",INDEX(A${R1}:A${R2},MATCH(MIN(E${R1}:E${R2}),E${R1}:E${R2},0)))`, 12, true).merge('B5:D5');
  sh.f('A6', `"Цена бездействия за "&B4&" дн.: "&ROUND(D4,1)&" млн ₽. С этой цифры начинаю разговор с собственником."`, 10, true).merge('A6:D6');
  sh.head(7, ['Позиция', 'Запас, дней', 'Что будет без поставки', 'Потери, млн ₽', 'Служебно']);
  for (let r = R1; r <= R2; r++) {
    sh.f(`A${r}`, `IF('Светофор'!A${r}="","",'Светофор'!A${r})`, 7, true).f(`B${r}`, `IF(A${r}="","",'Светофор'!D${r})`)
      .f(`C${r}`, `IF(A${r}="","",'Светофор'!C${r})`, 7, true)
      .f(`D${r}`, `IF(A${r}="","",MAX(0,$B$4-B${r})*'Светофор'!B${r}*${FACT(r)})`)
      .f(`E${r}`, `IF(A${r}="",9999,IF(D${r}>0,B${r},9999))`);
  }
  return sh;
}

export function checklistSheet(name, title, note, steps, done, banner) {
  const n = steps.length, r1 = 7, r2 = r1 + n - 1, C = `C${r1}:C${r2}`;
  const sh = new Sheet(name, [28, 72, 14]).title(title, note, 'A2:C2');
  if (banner) sh.f('A3', `IF(COUNTIF(${C},"Сделано")=${n},"Стабилизация пройдена. Можно открывать улучшения.","Улучшения заморожены. Сначала стабилизация.")`, 12, true).merge('A3:C3');
  sh.set('A4', 'Выполнено', 8).f('B4', `COUNTIF(${C},"Сделано")&" из ${n}"`, 8, true);
  sh.set('A5', 'Шаг на сегодня', 8).f('B5', `IFERROR(INDEX(B${r1}:B${r2},MATCH(TRUE,INDEX(${C}<>"Сделано",0),0)),"Все шаги закрыты")`, 12, true);
  sh.head(6, ['Этап', 'Шаг', 'Статус']);
  steps.forEach(([stage, text], i) => sh.set(`A${r1 + i}`, stage, 7).set(`B${r1 + i}`, text, 7).set(`C${r1 + i}`, done[i] ? 'Сделано' : null, 4));
  return sh.list(C, ['Сделано', 'В работе']).cond(C, [{ eq: 'Сделано', dxf: 2 }, { eq: 'В работе', dxf: 1 }]).cond(`B${r1}:B${r2}`, [{ expr: `B${r1}=$B$5`, dxf: 3 }]);
}

export function teamSheet(team) {
  const B = 'B7:B36', cnt = (d) => `"${d}: "&COUNTIF(${B},"${d}")`;
  const sh = new Sheet('Команда', [64, 16]).title('Разгрузка команды', 'Решите по каждому делу недели. Люди важнее красивых планов', 'A2:B2');
  sh.f('A3', TEAM_DECISIONS.map(cnt).join('&"   "&'), 8, true).merge('A3:B3');
  sh.f('A4', `"Красных "&'Светофор'!B4&" на "&'Параметры'!B7&" чел. "&IF('Светофор'!B4>'Параметры'!B7*3,"Перегруз: просите помощь или режьте список.","Нагрузка держится.")`, 12, true).merge('A4:B4');
  sh.head(6, ['Дело', 'Решение']);
  for (let r = 7; r <= 36; r++) sh.set(`A${r}`, team[r - 7]?.text, 4).set(`B${r}`, team[r - 7]?.decision, 4);
  return sh.list(B, TEAM_DECISIONS).cond(B, [{ eq: 'Оставить', dxf: 3 }, { eq: 'Передать', dxf: 2 }, { eq: 'Отложить', dxf: 1 }, { eq: 'Убрать', dxf: 4 }]);
}


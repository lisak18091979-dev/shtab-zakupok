const rg = (c) => `${c}${R1}:${c}${R2}`;
const FACT = (r) => `IF(C${r}="Остановит линию",1,IF(C${r}="Замедлит",'Параметры'!$B$5/100,0))`;
const num = (v) => (v === undefined ? null : +v);


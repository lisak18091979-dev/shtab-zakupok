import { Sheet } from './core';
import { THREE_FIELDS, DECISION_STATUSES } from '@/lib/shtab/defaults';

const LEVEL = `IF(COUNTA('Светофор'!A8:A57)=0,"ОЦЕНКА НЕ НАЧАТА: светофор пуст",IF(COUNTIF('Светофор'!G8:G57,"НЕПОЛНЫЕ ДАННЫЕ")>0,"ОЦЕНКА НЕ ЗАВЕРШЕНА: проверьте исходные данные",IF('Светофор'!B4>0,IF(COUNTIFS('Светофор'!G8:G57,"КРАСНОЕ",'Светофор'!L8:L57,"")>0,"ТРЕБУЕТСЯ ДЕЙСТВИЕ: красное без ответственного",IF(AND('Параметры'!B7<>"",'Светофор'!B4>'Параметры'!B7*3),"ПЕРЕГРУЗ: красного больше, чем рук","КРАСНОЕ В РАБОТЕ: контролируйте следующий шаг")),IF(COUNTIF('Светофор'!G8:G57,"ЖЁЛТОЕ")>0,"ВНИМАНИЕ: есть разрывы по жёлтым позициям","ЗАПАС ПОКРЫВАЕТ ЗАМЕНУ: проверенные позиции в зелёном"))))`;
const PENDING = `COUNTIF('Решения'!B6:B55,"Ждёт решения")`;

export function panelSheet() {
  const sh = new Sheet('Панель собственника', [54, 32]).title('Стабилизация выпуска', 'Поставки, исполнение плана и решения. Годовая экономия не является критерием стабилизации', 'A2:B2');
  sh.f('A4', LEVEL, 12, true).merge('A4:B4').cond('A4', [{ expr: 'LEFT($A$4,4)="ПЕРЕ"', dxf: 0 }, { expr: 'LEFT($A$4,4)="ЗАПА"', dxf: 2 }]);
  sh.head(6, ['Показатель', 'Значение']);
  [
    ['Красных позиций', `'Светофор'!B4`, 11],
    ['Позиции с неполными данными', `COUNTIF('Светофор'!G8:G57,"НЕПОЛНЫЕ ДАННЫЕ")`, 11],
    ['Красное без ответственного', `COUNTIFS('Светофор'!G8:G57,"КРАСНОЕ",'Светофор'!L8:L57,"")`, 11],
    ['Не хватает данных для оценки риска в рублях', `'Светофор'!H4`, 11],
    ['Шаги с препятствием или нужным решением', `COUNTIF('План 30 дней'!C7:C21,"Ждёт решения")+COUNTIF('72 часа'!C7:C17,"Ждёт решения")`, 11],
    ['Ждут вашего решения', PENDING, 11],
    ['Шагов плана стабилизации', `'План 30 дней'!B4`, 8],
  ].forEach(([label, f, s], i) => {
    const r = 7 + i;
    if (label) sh.set(`A${r}`, label, 8); else sh.f(`A${r}`, `"Потери при обрыве на "&'Параметры'!B6&" дн., млн ₽"`, 8, true);
    sh.f(`B${r}`, f, s, s === 8);
  });
  sh.set('A17', 'Первое ограничение в стресс-тесте:', 8).f('B17', `'Стресс тест'!B5`, 8, true);
  return sh.f('A18', `'Стресс тест'!A6`, 10, true).merge('A18:B18');
}

export function threeSheet(t) {
  const sh = new Sheet('Три цифры', [34, 12, 3, 46, 16, 62]).title('Три цифры вместо «экономии к цене»', 'Светлые ячейки заполняете вы. Справа считается язык собственника');
  sh.set('A4', 'Исходные данные', 3).set('B4', 'Значение', 3).set('D4', 'Цифра собственника', 3).set('E4', 'Значение', 3).set('F4', 'Пояснение', 3);
  THREE_FIELDS.forEach(([k, label], i) => sh.set(`A${5 + i}`, label, 8).set(`B${5 + i}`, t[k], 5));
  [
    ['1. Вклад в EBITDA в год, млн ₽', 'IF(COUNT(B5:B7)<3,"",B5*B6/100*B7/100)', 9, 'Подтверждённая часть экономии (EBITDA: прибыль до налогов, процентов и амортизации)'],
    ['2. Высвобождено из оборота, млн ₽', 'IF(COUNT(B5,B8,B9)<3,"",B5/365*(B8+B9))', 9, 'Единовременно, за счёт отсрочки и сокращения запасов'],
    ['   Проценты, которых не заплатим, млн ₽ в год', 'IF(COUNT(E6,B10)<2,"",E6*B10/100)', 6, 'Высвобожденные деньги по ставке компании'],
    ['3. Снижение риска в год, млн ₽', 'IF(COUNT(B11:B13)<3,"",MAX(0,B11-B12)*B13)', 9, 'Меньше дней срыва, умноженные на цену дня простоя'],
  ].forEach(([l, f, s, n], i) => sh.set(`D${5 + i}`, l, 8).f(`E${5 + i}`, f, s).set(`F${5 + i}`, n, 7));
  sh.set('D10', 'Не складывайте показатели автоматически: у них разная природа. Проверьте двойной счёт с финансами.', 7).merge('D10:F10');
  return sh;
}

export function decisionsSheet(decisions) {
  const B = 'B6:B55';
  const sh = new Sheet('Решения', [62, 18, 44]).title('Решения собственника', 'Закупщик вносит запрос, собственник выбирает статус из списка', 'A2:C2');
  sh.f('A3', DECISION_STATUSES.map((d) => `"${d}: "&COUNTIF(${B},"${d}")`).join('&"   "&'), 12, true).merge('A3:C3');
  sh.head(5, ['Запрос', 'Статус', 'Комментарий собственника']);
  for (let r = 6; r <= 55; r++) { const d = decisions[r - 6]; sh.set(`A${r}`, d?.text, 4).set(`B${r}`, d?.status, 4).set(`C${r}`, d?.comment, 4); }
  return sh.list(B, DECISION_STATUSES).cond(B, [{ eq: 'Ждёт решения', dxf: 1 }, { eq: 'Одобрено', dxf: 2 }, { eq: 'Отклонено', dxf: 0 }, { eq: 'Обсуждаем', dxf: 3 }]);
}

